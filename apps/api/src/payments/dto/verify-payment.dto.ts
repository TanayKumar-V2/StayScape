import { IsNotEmpty, IsString } from 'class-validator';
import { ApiProperty } from '@nestjs/swagger';

export class VerifyPaymentDto {
  @ApiProperty({
    description: 'Razorpay order ID generated by the backend order creation endpoint',
    example: 'order_EKwxwAgItmmMnv',
  })
  @IsString()
  @IsNotEmpty()
  razorpayOrderId!: string;

  @ApiProperty({
    description:
      'Razorpay payment ID returned by Checkout.js modal upon successful customer payment',
    example: 'pay_29MoEsz4rtouPt',
  })
  @IsString()
  @IsNotEmpty()
  razorpayPaymentId!: string;

  @ApiProperty({
    description: 'Cryptographic signature generated by Razorpay Checkout.js for verification',
    example: '9ef57245ef4c17c244585c5df600e5eb1d2274fc108d447d2a507ab3142718e0',
  })
  @IsString()
  @IsNotEmpty()
  razorpaySignature!: string;
}
